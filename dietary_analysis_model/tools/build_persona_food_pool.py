"""Build the persona food pool (data/persona_food_pool_v1.csv) from the per-serving MFDS reference.

Source: 01_Results/food_nutrient_reference_per_serving.csv (git-ignored, regenerated by
tools/build_food_reference.py). Only aggregated public reference rows are copied, so the pool
itself is small and tracked in git. The pool is the only food source the persona generator uses.

Usage:
	python tools/build_persona_food_pool.py [--source PATH] [--out data/persona_food_pool_v1.csv] [--seed 20261027]
"""

from __future__ import annotations

import argparse
import csv
import random
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "01_Results" / "food_nutrient_reference_per_serving.csv"
DEFAULT_OUT = ROOT / "data" / "persona_food_pool_v1.csv"

# major_name -> slot. Slots drive meal composition in the generator.
SLOT_BY_MAJOR = {
	"밥류": "STAPLE", "죽 및 스프류": "STAPLE", "곡류, 서류 제품": "STAPLE",
	"면 및 만두류": "NOODLE",
	"국 및 탕류": "SOUP", "찌개 및 전골류": "SOUP",
	"구이류": "SIDE", "조림류": "SIDE", "볶음류": "SIDE", "찜류": "SIDE", "전·적 및 부침류": "SIDE",
	"튀김류": "SIDE", "나물·숙채류": "SIDE", "생채·무침류": "SIDE", "김치류": "KIMCHI",
	"장아찌·절임류": "KIMCHI", "젓갈류": "KIMCHI",
	"빵 및 과자류": "BREAD", "과자류·빵류 또는 떡류": "BREAD",
	"음료 및 차류": "DRINK", "음료류": "DRINK",
	"유제품류 및 빙과류": "DAIRY", "유가공품류": "DAIRY",
}
# Rows per slot kept in the pool (deterministic sample).
CAP = {"STAPLE": 30, "NOODLE": 25, "SOUP": 40, "SIDE": 90, "KIMCHI": 15, "BREAD": 25, "DRINK": 20, "DAIRY": 15}
SNACK_SLOTS = {"BREAD", "DRINK", "DAIRY"}

NUTRIENTS = (
	"energy_kcal", "carbohydrate_g", "protein_g", "fat_g", "sugar_g", "dietary_fiber_g",
	"saturated_fat_g", "trans_fat_g", "cholesterol_mg", "sodium_mg", "potassium_mg", "calcium_mg",
	"phosphorus_mg", "iron_mg", "vitamin_a_ug", "vitamin_c_mg", "vitamin_d_ug", "vitamin_e_mg",
	"thiamin_mg", "riboflavin_mg", "niacin_mg",
)
OUT_COLUMNS = ("food_code", "food_name", "food_name_norm", "data_type", "major_name", "slot",
	"serving_qty", "serving_unit", *NUTRIENTS)


def norm_name(name: str) -> str:
	return re.sub(r"\s+", "", name).strip()


def _num(v: str) -> float | None:
	v = (v or "").strip()
	if v == "":
		return None
	try:
		return float(v)
	except ValueError:
		return None


def load_candidates(source: Path) -> dict[str, list[dict]]:
	by_slot: dict[str, list[dict]] = defaultdict(list)
	with source.open(encoding="utf-8-sig", newline="") as f:
		for row in csv.DictReader(f):
			if row["grade"] != "FULL" or row["quality_flag"].strip():
				continue
			slot = SLOT_BY_MAJOR.get(row["major_name"])
			if slot is None:
				continue
			if row["data_type"] == "가공식품" and slot not in SNACK_SLOTS:
				continue
			if row["data_type"] not in ("음식", "가공식품"):
				continue
			kcal = _num(row["energy_kcal_per_serving"])
			qty = _num(row["serving_qty"])
			if kcal is None or qty is None or qty <= 0:
				continue
			if not (15 <= kcal <= 1200) or (slot in SNACK_SLOTS and kcal > 400):
				continue
			# core macros must be present
			if any(_num(row[f"{c}_per_serving"]) is None for c in ("carbohydrate_g", "protein_g", "fat_g", "sodium_mg")):
				continue
			out = {
				"food_code": row["food_code"], "food_name": row["food_name"].strip(),
				"food_name_norm": norm_name(row["food_name"]), "data_type": row["data_type"],
				"major_name": row["major_name"], "slot": slot,
				"serving_qty": f"{qty:g}", "serving_unit": row["serving_unit"],
			}
			for c in NUTRIENTS:
				v = _num(row.get(f"{c}_per_serving", ""))
				out[c] = "" if v is None else f"{v:g}"
			by_slot[slot].append(out)
	return by_slot


def sample(by_slot: dict[str, list[dict]], seed: int) -> list[dict]:
	rng = random.Random(seed)
	rows: list[dict] = []
	for slot, cap in CAP.items():
		cands = sorted(by_slot.get(slot, []), key=lambda r: r["food_code"])
		# keep one row per normalised name so the pool has distinct dishes
		seen: set[str] = set()
		uniq = []
		for r in cands:
			if r["food_name_norm"] in seen:
				continue
			seen.add(r["food_name_norm"])
			uniq.append(r)
		rng.shuffle(uniq)
		rows.extend(sorted(uniq[:cap], key=lambda r: r["food_code"]))
	return rows


def main() -> None:
	ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	ap.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
	ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
	ap.add_argument("--seed", type=int, default=20261027)
	args = ap.parse_args()
	if not args.source.exists():
		raise SystemExit(f"source not found: {args.source} (run tools/build_food_reference.py first)")
	by_slot = load_candidates(args.source)
	rows = sample(by_slot, args.seed)
	args.out.parent.mkdir(parents=True, exist_ok=True)
	with args.out.open("w", encoding="utf-8", newline="") as f:
		w = csv.DictWriter(f, fieldnames=OUT_COLUMNS)
		w.writeheader()
		w.writerows(rows)
	counts = defaultdict(int)
	for r in rows:
		counts[r["slot"]] += 1
	print(f"wrote {len(rows)} rows -> {args.out}")
	for slot in CAP:
		print(f"  {slot:7s} {counts[slot]:3d} (candidates {len(by_slot.get(slot, []))})")


if __name__ == "__main__":
	main()
